#!/usr/bin/env python3
"""Emit the Sherpa catalog audit table for SHERPA_CATALOG_AUDIT.md (#92).

Reads the pinned sherpa-onnx-models registry (via Cargo.lock's crate
dir — pass the path to models.json as $1 if run outside the repo) and
prints one markdown section per model family: counts, language
coverage, download-source and checksum state, text front-end, and the
assets the wrapper expects on disk (from src/sherpaonnx_engine.rs's
config dispatch). Re-run when the registry crate bumps; paste the
output back into the audit doc.
"""
import json
import sys
from collections import Counter
from pathlib import Path

MODELS_JSON = sys.argv[1] if len(sys.argv) > 1 else str(
    next(Path.home().glob(
        ".cargo/registry/src/*/sherpa-onnx-models-*/models.json")))

PUBLISHED_BUNDLES = {
    "ca", "cs", "de", "en", "en-gb", "en-us", "es", "fa", "fr", "it",
    "nl", "pt", "ru", "sv", "sw",
}

# What the wrapper's synthesize() expects per family (see
# src/sherpaonnx_engine.rs config dispatch) and the text front-end it
# uses under sherpa-onnx 2.x.
FAMILY_PROFILE = {
    "vits": ("model.onnx + tokens.txt (+ espeak-ng-data, ignored; OR lexicon.txt / wrapper G2P)",
             "lexicon (ours) | wrapper phoneme_codepoints | model lexicon"),
    "mms": ("model.onnx + tokens.txt (+ lexicon.txt when bundled)",
            "character/lexicon front-end bundled with the model"),
    "kokoro": ("model.onnx + voices.bin + tokens.txt (+ lexicon-*.txt)",
               "bundled lexicons; missing locales dropped (#4139)"),
    "kitten": ("model.onnx + voices.bin + tokens.txt + lexicon*.txt",
               "bundled lexicon required"),
    "matcha": ("acoustic-model.onnx + vocoder.onnx + tokens.txt + lexicon.txt",
               "bundled lexicon required"),
    "zipvoice": ("encoder/decoder .onnx + tokens.txt + lexicon.txt + vocos vocoder",
                 "bundled lexicon; zero-shot cloning"),
    "pocket": ("lm_flow/lm_main/encoder/decoder/text_conditioner .onnx + vocab.json",
               "own tokenizer; zero-shot cloning"),
    "supertonic": ("tts json + model.onnx", "own front-end"),
    "floravox-student": ("model.onnx + tokens.txt + lexicon.txt",
                         "bundled lexicon required"),
    "(none)": ("vits layout (see vits)", "as vits"),
}


def main() -> None:
    registry = json.loads(Path(MODELS_JSON).read_text())
    fam_counts: Counter = Counter(
        (m.get("model_type") or "(none)") for m in registry.values())

    print("<!-- generated by scripts/sherpa-catalog-audit.py — regenerate on registry bumps -->\n")
    for fam, count in fam_counts.most_common():
        models = {i: m for i, m in registry.items()
                  if (m.get("model_type") or "(none)") == fam}
        urls = sum(1 for m in models.values()
                   if str(m.get("url", "")).startswith("http"))
        shas = sum(1 for m in models.values() if m.get("sha256"))
        deprec = sum(1 for m in models.values() if m.get("deprecated"))
        langs = Counter()
        for m in models.values():
            for l in (m.get("language") or []):
                langs[l["lang_code"].lower()] += 1
        assets, frontend = FAMILY_PROFILE.get(fam, ("?", "?"))
        top_langs = ", ".join(f"{k}×{v}" for k, v in langs.most_common(8))
        print(f"### {fam or '(none)'} — {count} models\n")
        print(f"- assets: {assets}")
        print(f"- text front-end: {frontend}")
        print(f"- download url: {urls}/{count} · sha256: {shas}/{count}"
              f" · deprecated: {deprec}")
        if langs:
            print(f"- languages: {top_langs}"
                  + (" …" if len(langs) > 8 else ""))

        # bundle opportunity: non-English piper/vits locales with a
        # published VoiceGarden bundle
        if fam in ("vits", "(none)"):
            covered = Counter()
            for mid, m in models.items():
                for l in (m.get("language") or []):
                    c = l["lang_code"].lower()
                    if c in PUBLISHED_BUNDLES and c not in ("en", "en-us", "en-gb"):
                        covered[c] += 1
            if covered:
                row = ", ".join(f"{k}×{v}" for k, v in covered.most_common())
                print(f"- VoiceGarden-bundle locales (wrapper G2P ready "
                      f"to validate): {row}")
        print()

    # languages WITHOUT bundles (gap list)
    gap = Counter()
    for m in registry.values():
        if (m.get("model_type") or "(none)") not in ("vits", "(none)"):
            continue
        for l in (m.get("language") or []):
            c = l["lang_code"].lower()
            if len(c) == 2 and c not in PUBLISHED_BUNDLES and c != "zh":
                gap[c] += 1
    print("### gap: vits/piper languages with no published bundle\n")
    print(", ".join(f"{k}×{v}" for k, v in gap.most_common()))
    print("\n(zh uses its own dict/jieba front-end — bundles do not apply)\n")


if __name__ == "__main__":
    main()
